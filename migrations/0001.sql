CREATE TABLE IF NOT EXISTS shares (id TEXT PRIMARY KEY, payload TEXT NOT NULL, expires INTEGER NOT NULL, remaining INTEGER NOT NULL CHECK(remaining >= 0));
CREATE INDEX IF NOT EXISTS shares_expiry ON shares(expires);
CREATE TABLE IF NOT EXISTS visits (id INTEGER PRIMARY KEY AUTOINCREMENT, ts INTEGER NOT NULL, device TEXT NOT NULL, country TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS visits_time ON visits(ts);
CREATE TABLE IF NOT EXISTS rate_limits (id TEXT PRIMARY KEY, count INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS rate_expiry ON rate_limits(expires);
